// =====================================================
// ELEMENT WEBSITE
// =====================================================

const categoryGrid = document.getElementById('categoryGrid');

const detail = document.getElementById('catalog-detail');

const detailTitle = document.getElementById('detailTitle');

const detailDescription = document.getElementById('detailDescription');

const detailContent = document.getElementById('detailContent');

const closeDetail = document.getElementById('closeDetail');


// =====================================================
// RENDER 8 CATEGORY CARD
// =====================================================

function renderCards() {

  categoryGrid.innerHTML = categories.map((item, index) => {

    return `
      <article
        class="catalog-card"
        data-id="${item.id}"
      >

        <img
          class="catalog-card-image"
          src="${item.image}"
          alt="${item.name}"
        >

        <div class="catalog-card-overlay"></div>

        <div class="catalog-number">
          ${String(index + 1).padStart(2, '0')}
        </div>

        <div class="catalog-card-info">

          <h3>${item.name}</h3>

          <p>${item.desc}</p>

        </div>

        <span class="catalog-arrow">
          ↗
        </span>

      </article>
    `;

  }).join('');


  // Event klik
  categoryGrid
    .querySelectorAll('.catalog-card')
    .forEach(card => {

      card.addEventListener('click', () => {

        openCategory(card.dataset.id);

      });

    });

}


// =====================================================
// OPEN CATEGORY
// =====================================================

function openCategory(id) {

  const item = categories.find(
    category => category.id === id
  );

  if (!item) return;


  // Card selected
  categoryGrid
    .querySelectorAll('.catalog-card')
    .forEach(card => {

      card.classList.toggle(
        'selected',
        card.dataset.id === item.id
      );

    });


  // Judul
  detailTitle.textContent = item.name;


  // Deskripsi
  detailDescription.textContent = item.desc;


  // ===================================================
  // JIKA BELUM ADA VARIASI
  // ===================================================

  if (
    !item.variations ||
    item.variations.length === 0
  ) {

    detailContent.innerHTML = `

      <div class="detail-empty">

        <div>

          <strong>
            Katalog ${item.name}
          </strong>

          <span>
            Variasi desain untuk kategori ini
            belum ditambahkan.
          </span>

        </div>

      </div>

    `;

  }


  // ===================================================
  // JIKA ADA VARIASI
  // ===================================================

  else {

    detailContent.innerHTML = item.variations
      .map((variation, index) => {

        return `

          <div class="variation-card">

            <div class="variation-image">

              <img
                src="${variation.image}"
                alt="${variation.name}"
                loading="lazy"
              >

            </div>

            <div class="variation-info">

              <span>
                ${String(index + 1).padStart(2, '0')}
              </span>

              <h3>
                ${variation.name}
              </h3>

            </div>

          </div>

        `;

      })
      .join('');

  }


  // Tampilkan detail
  detail.classList.add('open');


  // Scroll
  setTimeout(() => {

    detail.scrollIntoView({
      behavior: 'smooth',
      block: 'start'
    });

  }, 30);


  // URL
  history.replaceState(
    null,
    '',
    `katalog.html?category=${item.id}`
  );

}


// =====================================================
// CLOSE
// =====================================================

closeDetail.addEventListener('click', () => {

  detail.classList.remove('open');

  categoryGrid
    .querySelectorAll('.catalog-card')
    .forEach(card => {

      card.classList.remove('selected');

    });

  history.replaceState(
    null,
    '',
    'katalog.html'
  );

});


// =====================================================
// INITIAL RENDER
// =====================================================

renderCards();


// =====================================================
// OPEN FROM URL
// =====================================================

const params = new URLSearchParams(
  window.location.search
);

const initialCategory = params.get('category');

if (initialCategory) {

  openCategory(initialCategory);

}